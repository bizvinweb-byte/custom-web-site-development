// Helper to look up a city by either full slug or short slug
export function getCityBySlug(slug) {
  if (!slug) return null;
  const normalized = slug.toLowerCase().trim();
  return (
    citiesData.find(
      (c) => c.slug === normalized || c.shortSlug === normalized
    ) || null
  );
}

// Get all possible slugs for generateStaticParams
export function getAllCitySlugs() {
  const slugs = [];
  citiesData.forEach((city) => {
    slugs.push({ slug: city.slug });
    slugs.push({ slug: city.shortSlug });
  });
  return slugs;
}

